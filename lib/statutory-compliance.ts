// Indian statutory compliance calendar + filing tracker + board approvals + reminders.
// Deadlines encoded per current Indian law for a Karnataka-registered private limited company:
//   GSTR-1   : 11th of the following month (monthly filer)
//   GSTR-3B  : 20th of the following month (monthly filer)
//   GSTR-9   : 31 December following the financial year (annual)
//   TDS deposit: 7th of the following month; EXCEPTION - March TDS deposits by 30 April
//   TDS returns: 24Q (salary) & 26Q (non-salary), quarterly - 31 Jul / 31 Oct / 31 Jan / 31 May
//   EPF + ESI : 15th of the following month
//   Professional Tax (Karnataka Form 5A): 20th of the following month
//   Advance tax: 15 Jun (15%), 15 Sep (45%), 15 Dec (75%), 15 Mar (100%) cumulative
//   ROC annual: AOC-4 within 30 days of AGM, MGT-7 within 60 days (standard 30 Oct / 29 Nov)
//   Board: Companies Act 2013 s173 requires 4 meetings/yr, gap <= 120 days; the founder wants a
//   MONTHLY board approval of the management accounts so every filing rides on approved numbers.
// Filing itself stays manual (a human files on the govt portal and records the acknowledgement) -
// this module makes the deadline impossible to miss and the numbers ready.

type Db=D1Database;
type Row=Record<string,unknown>;

export type ObligationCode="gstr1"|"gstr3b"|"gstr9"|"tds_deposit"|"tds_return_24q"|"tds_return_26q"|"epf"|"esi"|"professional_tax"|"advance_tax"|"roc_aoc4"|"roc_mgt7"|"board_approval";
export type ObligationStatus="upcoming"|"due_soon"|"overdue"|"filed";
export type StatutoryObligation={code:ObligationCode;label:string;authority:string;period:string;dueDate:string;kind:"monthly"|"quarterly"|"annual";notes:string};

const pad=(value:number)=>String(value).padStart(2,"0");
export const periodKey=(year:number,month:number)=>`${year}-${pad(month)}`;
const nextMonth=(year:number,month:number)=>month===12?{year:year+1,month:1}:{year,month:month+1};

/** Indian FY quarter for a calendar month: Q1=Apr-Jun ... Q4=Jan-Mar. */
export function fyQuarter(year:number,month:number):{quarter:1|2|3|4;fyLabel:string;quarterEnd:{year:number;month:number}}{
 if(month>=4&&month<=6)return{quarter:1,fyLabel:`FY${year}-${(year+1)%100}`,quarterEnd:{year,month:6}};
 if(month>=7&&month<=9)return{quarter:2,fyLabel:`FY${year}-${(year+1)%100}`,quarterEnd:{year,month:9}};
 if(month>=10&&month<=12)return{quarter:3,fyLabel:`FY${year}-${(year+1)%100}`,quarterEnd:{year,month:12}};
 return{quarter:4,fyLabel:`FY${year-1}-${year%100}`,quarterEnd:{year,month:3}};
}

/** Every statutory obligation generated by activity in calendar month `period` ("YYYY-MM"). Pure. */
export function statutoryObligationsFor(period:string):StatutoryObligation[]{
 const[yearText,monthText]=period.split("-"),year=Number(yearText),month=Number(monthText);
 if(!Number.isInteger(year)||!Number.isInteger(month)||month<1||month>12)throw new Error("Period must be YYYY-MM");
 const next=nextMonth(year,month),obligations:StatutoryObligation[]=[
  {code:"board_approval",label:`Board approval of ${period} management accounts`,authority:"Board of Directors",period,dueDate:`${next.year}-${pad(next.month)}-05`,kind:"monthly",notes:"Founder policy: monthly board approval so every filing rides on approved numbers (Companies Act s173 minimum is quarterly)"},
  {code:"gstr1",label:`GSTR-1 for ${period}`,authority:"GST",period,dueDate:`${next.year}-${pad(next.month)}-11`,kind:"monthly",notes:"Outward supplies statement"},
  {code:"gstr3b",label:`GSTR-3B for ${period}`,authority:"GST",period,dueDate:`${next.year}-${pad(next.month)}-20`,kind:"monthly",notes:"Summary return + tax payment"},
  {code:"tds_deposit",label:`TDS deposit for ${period}`,authority:"Income Tax",period,dueDate:month===3?`${year}-04-30`:`${next.year}-${pad(next.month)}-07`,kind:"monthly",notes:month===3?"March exception: deposit by 30 April":"Challan ITNS-281 by the 7th"},
  {code:"epf",label:`EPF remittance for ${period}`,authority:"EPFO",period,dueDate:`${next.year}-${pad(next.month)}-15`,kind:"monthly",notes:"Employee + employer PF contribution"},
  {code:"esi",label:`ESI remittance for ${period}`,authority:"ESIC",period,dueDate:`${next.year}-${pad(next.month)}-15`,kind:"monthly",notes:"Applicable while any employee is within the ESI wage ceiling"},
  {code:"professional_tax",label:`Karnataka Professional Tax for ${period}`,authority:"Karnataka CT",period,dueDate:`${next.year}-${pad(next.month)}-20`,kind:"monthly",notes:"Form 5A monthly statement"},
 ];
 // Quarterly TDS returns attach to the quarter-END month.
 const q=fyQuarter(year,month);
 if(month===q.quarterEnd.month){
  const due=q.quarter===1?`${year}-07-31`:q.quarter===2?`${year}-10-31`:q.quarter===3?`${year+1}-01-31`:`${year}-05-31`;
  const qPeriod=`${q.fyLabel}-Q${q.quarter}`;
  obligations.push(
   {code:"tds_return_24q",label:`TDS return 24Q (salaries) ${qPeriod}`,authority:"Income Tax",period:qPeriod,dueDate:due,kind:"quarterly",notes:"Quarterly salary TDS return"},
   {code:"tds_return_26q",label:`TDS return 26Q (non-salary) ${qPeriod}`,authority:"Income Tax",period:qPeriod,dueDate:due,kind:"quarterly",notes:"Quarterly non-salary TDS return (194C/194H/194J...)"},
  );
 }
 // Advance tax instalments fall IN the month they are due.
 const advance:{[key:number]:{pct:number;due:string}}={6:{pct:15,due:`${year}-06-15`},9:{pct:45,due:`${year}-09-15`},12:{pct:75,due:`${year}-12-15`},3:{pct:100,due:`${year}-03-15`}};
 if(advance[month])obligations.push({code:"advance_tax",label:`Advance tax instalment (${advance[month].pct}% cumulative)`,authority:"Income Tax",period,dueDate:advance[month].due,kind:"quarterly",notes:"Cumulative corporate advance tax"});
 // Annual obligations attach to their calendar month.
 if(month===12)obligations.push({code:"gstr9",label:`GSTR-9 annual return FY${year-1}-${year%100}`,authority:"GST",period:`FY${year-1}-${year%100}`,dueDate:`${year}-12-31`,kind:"annual",notes:"Annual GST return for the previous financial year"});
 if(month===10)obligations.push({code:"roc_aoc4",label:"ROC AOC-4 (financial statements)",authority:"MCA",period:`FY${year-1}-${year%100}`,dueDate:`${year}-10-30`,kind:"annual",notes:"Within 30 days of AGM (standard calendar)"});
 if(month===11)obligations.push({code:"roc_mgt7",label:"ROC MGT-7 (annual return)",authority:"MCA",period:`FY${year-1}-${year%100}`,dueDate:`${year}-11-29`,kind:"annual",notes:"Within 60 days of AGM (standard calendar)"});
 return obligations;
}

const statutoryTablesEnsured=new WeakSet<Db>();
export async function ensureStatutoryTables(db:Db){
 if(statutoryTablesEnsured.has(db))return;
 await db.batch([
  db.prepare("CREATE TABLE IF NOT EXISTS statutory_filings (id TEXT PRIMARY KEY,obligation_code TEXT NOT NULL,period TEXT NOT NULL,due_date TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'pending',amount REAL,acknowledgement_ref TEXT,filed_by TEXT,filed_at INTEGER,notes TEXT,created_at INTEGER NOT NULL,updated_at INTEGER NOT NULL,UNIQUE(obligation_code,period))"),
  db.prepare("CREATE INDEX IF NOT EXISTS idx_statutory_due ON statutory_filings(status,due_date)"),
  db.prepare("CREATE TABLE IF NOT EXISTS board_approvals (id TEXT PRIMARY KEY,period TEXT NOT NULL UNIQUE,resolution_type TEXT NOT NULL DEFAULT 'monthly_accounts',approved_by TEXT NOT NULL,approver_role TEXT NOT NULL,minutes_reference TEXT,resolution_text TEXT NOT NULL,approved_at INTEGER NOT NULL,created_at INTEGER NOT NULL)"),
  db.prepare("CREATE TABLE IF NOT EXISTS statutory_events (id TEXT PRIMARY KEY,obligation_code TEXT NOT NULL,period TEXT NOT NULL,event_type TEXT NOT NULL,actor_id TEXT NOT NULL,detail_json TEXT NOT NULL DEFAULT '{}',created_at INTEGER NOT NULL)"),
 ]);
 statutoryTablesEnsured.add(db);
}

export type ObligationView=StatutoryObligation&{status:ObligationStatus;daysToDue:number;filedAt:number|null;acknowledgementRef:string|null;amount:number|null};

/** Calendar for a period with live status against recorded filings. */
export async function statutoryCalendar(db:Db,period:string,asOf=Date.now()):Promise<ObligationView[]>{
 await ensureStatutoryTables(db);
 const obligations=statutoryObligationsFor(period);
 const filings=await db.prepare("SELECT * FROM statutory_filings WHERE period IN ("+obligations.map(()=>"?").join(",")+") OR period=?").bind(...obligations.map(o=>o.period),period).all<Row>();
 const filedBy=new Map<string,Row>();for(const row of filings.results)filedBy.set(`${row.obligation_code}:${row.period}`,row);
 return obligations.map(obligation=>{
  const filing=filedBy.get(`${obligation.code}:${obligation.period}`)||null;
  const dueMs=new Date(`${obligation.dueDate}T23:59:59+05:30`).getTime();
  const daysToDue=Math.floor((dueMs-asOf)/86_400_000);
  const status:ObligationStatus=filing&&String(filing.status)==="filed"?"filed":asOf>dueMs?"overdue":daysToDue<=7?"due_soon":"upcoming";
  return{...obligation,status,daysToDue,filedAt:filing?.filed_at?Number(filing.filed_at):null,acknowledgementRef:filing?.acknowledgement_ref?String(filing.acknowledgement_ref):null,amount:filing?.amount==null?null:Number(filing.amount)};
 });
}

export async function recordStatutoryFiling(db:Db,input:{obligationCode:ObligationCode;period:string;acknowledgementRef:string;amount?:number;notes?:string;actorId:string;asOf?:number}){
 await ensureStatutoryTables(db);
 const ack=String(input.acknowledgementRef||"").trim();
 if(!ack)throw new Response("A government acknowledgement reference is required to record a filing",{status:400});
 const known=statutoryObligationsFor(/^\d{4}-\d{2}$/.test(input.period)?input.period:new Date().toISOString().slice(0,7));
 const match=known.find(o=>o.code===input.obligationCode&&o.period===input.period);
 const dueDate=match?.dueDate??null;
 const now=input.asOf??Date.now();
 await db.prepare("INSERT INTO statutory_filings (id,obligation_code,period,due_date,status,amount,acknowledgement_ref,filed_by,filed_at,notes,created_at,updated_at) VALUES (?,?,?,?,'filed',?,?,?,?,?,?,?) ON CONFLICT(obligation_code,period) DO UPDATE SET status='filed',amount=excluded.amount,acknowledgement_ref=excluded.acknowledgement_ref,filed_by=excluded.filed_by,filed_at=excluded.filed_at,notes=excluded.notes,updated_at=excluded.updated_at")
  .bind(`STF-${crypto.randomUUID().slice(0,10).toUpperCase()}`,input.obligationCode,input.period,dueDate??"",input.amount??null,ack,input.actorId,now,input.notes??null,now,now).run();
 await db.prepare("INSERT INTO statutory_events (id,obligation_code,period,event_type,actor_id,detail_json,created_at) VALUES (?,?,?,?,?,?,?)")
  .bind(`STE-${crypto.randomUUID().slice(0,10).toUpperCase()}`,input.obligationCode,input.period,"filed",input.actorId,JSON.stringify({acknowledgementRef:ack,amount:input.amount??null}),now).run();
 return{obligationCode:input.obligationCode,period:input.period,status:"filed" as const,acknowledgementRef:ack};
}

export async function recordBoardApproval(db:Db,input:{period:string;approvedBy:string;approverRole:string;minutesReference?:string;resolutionText?:string;asOf?:number}){
 await ensureStatutoryTables(db);
 if(!/^\d{4}-\d{2}$/.test(input.period))throw new Response("Board approval period must be YYYY-MM",{status:400});
 const now=input.asOf??Date.now();
 const existing=await db.prepare("SELECT id,approved_by,approved_at FROM board_approvals WHERE period=?").bind(input.period).first<Row>();
 if(existing)return{period:input.period,approvedBy:String(existing.approved_by),approvedAt:Number(existing.approved_at),duplicatePrevented:true};
 const text=input.resolutionText??`RESOLVED THAT the management accounts of PawSpace for ${input.period}, having been reviewed, are approved and taken on record; statutory filings for the period may proceed on these numbers.`;
 await db.prepare("INSERT INTO board_approvals (id,period,resolution_type,approved_by,approver_role,minutes_reference,resolution_text,approved_at,created_at) VALUES (?,?,?,?,?,?,?,?,?)")
  .bind(`BRD-${crypto.randomUUID().slice(0,10).toUpperCase()}`,input.period,"monthly_accounts",input.approvedBy,input.approverRole,input.minutesReference??null,text,now,now).run();
 await recordStatutoryFiling(db,{obligationCode:"board_approval",period:input.period,acknowledgementRef:input.minutesReference??`BOARD-${input.period}`,actorId:input.approvedBy,asOf:now});
 return{period:input.period,approvedBy:input.approvedBy,approvedAt:now,duplicatePrevented:false};
}

export async function getBoardApproval(db:Db,period:string){
 await ensureStatutoryTables(db);
 const row=await db.prepare("SELECT * FROM board_approvals WHERE period=?").bind(period).first<Row>();
 return row?{period:String(row.period),approvedBy:String(row.approved_by),approverRole:String(row.approver_role),minutesReference:row.minutes_reference?String(row.minutes_reference):null,resolutionText:String(row.resolution_text),approvedAt:Number(row.approved_at)}:null;
}

/** Reminder sweep: unfiled obligations due within `windowDays` (or overdue) for the current and
 *  previous activity month become staff alerts. Idempotent per obligation+period+bucket. */
export async function runStatutoryReminderSweep(db:Db,input:{asOf?:number;windowDays?:number}={}){
 await ensureStatutoryTables(db);
 const asOf=input.asOf??Date.now(),windowDays=input.windowDays??7;
 const at=new Date(asOf);
 const current=periodKey(at.getUTCFullYear(),at.getUTCMonth()+1);
 const previous=at.getUTCMonth()===0?periodKey(at.getUTCFullYear()-1,12):periodKey(at.getUTCFullYear(),at.getUTCMonth());
 const due:Array<ObligationView&{bucket:string}>=[];
 for(const period of[previous,current]){
  for(const item of await statutoryCalendar(db,period,asOf)){
   if(item.status==="filed")continue;
   if(item.status==="overdue")due.push({...item,bucket:"overdue"});
   else if(item.daysToDue<=windowDays)due.push({...item,bucket:`T-${Math.max(0,item.daysToDue)}`});
  }
 }
 // Same staff_alerts shape the rest of the platform uses (lib/staff-alert-center.ts DDL).
 await db.batch([db.prepare("CREATE TABLE IF NOT EXISTS staff_alerts (id TEXT PRIMARY KEY,idempotency_key TEXT NOT NULL UNIQUE,alert_type TEXT NOT NULL,severity TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'open',source_type TEXT NOT NULL,source_id TEXT NOT NULL,title TEXT NOT NULL,body TEXT NOT NULL,team_code TEXT,recipient_role TEXT,recipient_email TEXT,customer_id TEXT,booking_id TEXT,lead_id TEXT,case_id TEXT,due_at INTEGER NOT NULL,acknowledged_at INTEGER,acknowledged_by TEXT,resolved_at INTEGER,resolved_by TEXT,created_at INTEGER NOT NULL,updated_at INTEGER NOT NULL)")]);
 let created=0;
 for(const item of due){
  const idempotencyKey=`statutory:${item.code}:${item.period}:${item.bucket}`;
  const severity=item.bucket==="overdue"?"critical":item.daysToDue<=3?"high":"medium";
  const result=await db.prepare("INSERT OR IGNORE INTO staff_alerts (id,idempotency_key,alert_type,severity,status,source_type,source_id,title,body,recipient_role,due_at,created_at,updated_at) VALUES (?,?,?,?,'open','statutory_obligation',?,?,?,?,?,?,?)")
   .bind(`SAL-${crypto.randomUUID().slice(0,10).toUpperCase()}`,idempotencyKey,"statutory_reminder",severity,`${item.code}:${item.period}`,item.bucket==="overdue"?`OVERDUE: ${item.label}`:`${item.label} due ${item.dueDate}`,`${item.authority} · due ${item.dueDate} · ${item.notes}`,"finance",new Date(`${item.dueDate}T23:59:59+05:30`).getTime(),asOf,asOf).run();
  created+=Number(result.meta.changes||0);
 }
 return{asOf,checked:due.length,created,periods:[previous,current]};
}
